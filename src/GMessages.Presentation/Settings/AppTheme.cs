namespace GMessages.Presentation.Settings;

/// <summary>
/// Specifies the app theme. Ported from Magic Buds.
/// </summary>
public enum AppTheme
{
    /// <summary>
    /// The app follows the Windows theme.
    /// </summary>
    System,

    /// <summary>
    /// The app is always light.
    /// </summary>
    Light,

    /// <summary>
    /// The app is always dark.
    /// </summary>
    Dark,
}
